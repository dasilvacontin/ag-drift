function x2 (matrix) {
  const newMap = []
  matrix.forEach(row => {
    const newRow1 = []
    const newRow2 = []
    row.forEach(cell => {
      newRow1.push(cell)
      newRow1.push(cell)
      newRow2.push(cell)
      newRow2.push(cell)
    })
    newMap.push(newRow1)
    newMap.push(newRow2)
  })
  return newMap
}
